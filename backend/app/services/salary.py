"""Monthly payroll from salary structures, teacher attendance and advances.

net = gross - absence deduction - advances, where absence deduction = gross / days in month x days marked
`absent` (`leave` and `late` are not deducted). Generating a month again recalculates its unpaid records
and never touches paid ones."""

import calendar
import uuid
from datetime import date
from decimal import Decimal

from sqlalchemy import func, select, true
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.errors import conflict, forbidden, invalid, not_found
from app.core.permissions import SCHOOL_WIDE
from app.models import Role, SalaryAdvance, SalaryRecord, SalaryStructure, Teacher, TeacherAttendance, User
from app.models.enums import SalaryStatus, TeacherAttendanceStatus
from app.schemas.salary import AdvanceIn, AdvanceOut, GenerateOut, SalaryRecordOut
from app.services.audit import log_action
from app.services.dbutil import flush_or_conflict
from app.services.notify import notify
from app.services.payments import school_today
from app.services.scoping import teacher_id_for
from app.utils.money import money

ZERO = Decimal(0)


def _month_bounds(month: date) -> tuple[date, date]:
    first = month.replace(day=1)
    return first, first.replace(day=calendar.monthrange(first.year, first.month)[1])


def compute_net(gross: Decimal, absent_days: int, days_in_month: int, advances: Decimal) -> tuple[Decimal, Decimal]:
    """Returns (absence_deduction, net); net never goes below zero."""
    deduction = money(gross / days_in_month * absent_days)
    return deduction, max(money(gross - deduction - advances), money(0))


async def _month_inputs(db: AsyncSession, first: date, last: date, teacher_id: uuid.UUID | None = None):
    """(teacher, structure) rows, absent-day counts and advance totals for one month."""
    only = (lambda col: col == teacher_id) if teacher_id else (lambda col: true())
    teachers = (
        await db.execute(
            select(Teacher, SalaryStructure)
            .outerjoin(SalaryStructure, SalaryStructure.teacher_id == Teacher.id)
            .where(Teacher.is_deleted.is_(False), only(Teacher.id))
            .order_by(Teacher.employee_id)
        )
    ).all()
    absences = dict(
        (
            await db.execute(
                select(TeacherAttendance.teacher_id, func.count())
                .where(
                    TeacherAttendance.date.between(first, last),
                    TeacherAttendance.status == TeacherAttendanceStatus.ABSENT,
                    only(TeacherAttendance.teacher_id),
                )
                .group_by(TeacherAttendance.teacher_id)
            )
        ).all()
    )
    advances = dict(
        (
            await db.execute(
                select(SalaryAdvance.teacher_id, func.sum(SalaryAdvance.amount))
                .where(SalaryAdvance.month == first, only(SalaryAdvance.teacher_id))
                .group_by(SalaryAdvance.teacher_id)
            )
        ).all()
    )
    return teachers, absences, advances


def _values(structure: SalaryStructure, absent: int, advance, days_in_month: int) -> dict:
    gross = money(structure.basic + structure.house + structure.transport + structure.medical)
    advance = money(advance or 0)
    deduction, net = compute_net(gross, absent, days_in_month, advance)
    return dict(gross=gross, absent_days=absent, absence_deduction=deduction, advance_deduction=advance, net=net)


async def generate_month(db: AsyncSession, actor: User, month: date, ip: str | None) -> GenerateOut:
    first, last = _month_bounds(month)
    teachers, absences, advances = await _month_inputs(db, first, last)
    existing = {
        r.teacher_id: r
        for r in await db.scalars(select(SalaryRecord).where(SalaryRecord.month == first).with_for_update())
    }
    out = GenerateOut(created=0, recalculated=0, skipped_paid=0, without_structure=[])
    for teacher, structure in teachers:
        if structure is None:
            out.without_structure.append(teacher.full_name)
            continue
        record = existing.get(teacher.id)
        if record is not None and record.status == SalaryStatus.PAID:
            out.skipped_paid += 1
            continue
        values = _values(structure, absences.get(teacher.id, 0), advances.get(teacher.id), last.day)
        if record is None:
            db.add(SalaryRecord(teacher_id=teacher.id, month=first, status=SalaryStatus.UNPAID, **values))
            out.created += 1
        else:
            for k, v in values.items():
                setattr(record, k, v)
            out.recalculated += 1
    await flush_or_conflict(db, "This month is being generated by someone else; try again.", code="busy")
    log_action(actor, "generate", "salary_month", None, {"month": str(first), **out.model_dump()}, db=db, ip=ip)
    await db.commit()
    return out


def _records_stmt():
    return select(SalaryRecord, Teacher.full_name, Teacher.employee_id).join(
        Teacher, Teacher.id == SalaryRecord.teacher_id
    )


def _record_out(row) -> SalaryRecordOut:
    r, name, emp = row
    return SalaryRecordOut(
        id=r.id,
        teacher_id=r.teacher_id,
        teacher_name=name,
        employee_id=emp,
        month=r.month,
        gross=r.gross,
        absent_days=r.absent_days,
        absence_deduction=r.absence_deduction,
        advance_deduction=r.advance_deduction,
        net=r.net,
        status=r.status,
        paid_date=r.paid_date,
    )


async def list_month(db: AsyncSession, month: date) -> list[SalaryRecordOut]:
    first, _ = _month_bounds(month)
    rows = await db.execute(_records_stmt().where(SalaryRecord.month == first).order_by(Teacher.employee_id))
    return [_record_out(r) for r in rows.all()]


async def my_records(db: AsyncSession, user: User) -> list[SalaryRecordOut]:
    teacher_id = await teacher_id_for(db, user)
    if teacher_id is None:
        raise not_found("Teacher profile")
    rows = await db.execute(
        _records_stmt().where(SalaryRecord.teacher_id == teacher_id).order_by(SalaryRecord.month.desc())
    )
    return [_record_out(r) for r in rows.all()]


async def get_record(db: AsyncSession, user: User, record_id: uuid.UUID) -> SalaryRecordOut:
    stmt = _records_stmt().where(SalaryRecord.id == record_id)
    if user.role not in SCHOOL_WIDE:
        if user.role != Role.TEACHER:
            raise forbidden()
        stmt = stmt.where(SalaryRecord.teacher_id == await teacher_id_for(db, user))
    row = (await db.execute(stmt)).one_or_none()
    if row is None:
        raise not_found("Salary record")
    return _record_out(row)


async def mark_paid(
    db: AsyncSession, actor: User, record_id: uuid.UUID, paid_date: date | None, ip: str | None
) -> SalaryRecordOut:
    record = await db.scalar(select(SalaryRecord).where(SalaryRecord.id == record_id).with_for_update())
    if record is None:
        raise not_found("Salary record")
    if record.status == SalaryStatus.PAID:
        raise conflict("This salary is already paid.", code="already_paid")
    # pay what is owed now: advances or attendance may have changed since the month was generated
    first, last = _month_bounds(record.month)
    teachers, absences, advances = await _month_inputs(db, first, last, record.teacher_id)
    if teachers and teachers[0][1] is not None:
        for k, v in _values(
            teachers[0][1], absences.get(record.teacher_id, 0), advances.get(record.teacher_id), last.day
        ).items():
            setattr(record, k, v)
    record.status, record.paid_date = SalaryStatus.PAID, paid_date or await school_today(db)
    teacher = await db.get(Teacher, record.teacher_id)
    await notify(db, [teacher.user_id], f"Your salary for {record.month:%B %Y} has been paid.", "salary")
    log_action(
        actor, "pay", "salary_record", record.id, {"net": str(record.net), "month": str(record.month)}, db=db, ip=ip
    )
    await db.commit()
    return await get_record(db, actor, record.id)


# --- advances ------------------------------------------------------------------------------------


async def _month_paid(db: AsyncSession, teacher_id: uuid.UUID, month: date) -> bool:
    """Locks the month's record (if any) so a concurrent `mark_paid` waits for this advance change."""
    status = await db.scalar(
        select(SalaryRecord.status)
        .where(SalaryRecord.teacher_id == teacher_id, SalaryRecord.month == month)
        .with_for_update()
    )
    return status == SalaryStatus.PAID


async def add_advance(db: AsyncSession, actor: User, body: AdvanceIn, ip: str | None) -> AdvanceOut:
    teacher = await db.get(Teacher, body.teacher_id)
    if teacher is None or teacher.is_deleted:
        raise invalid("Unknown teacher.", {"teacher_id": "Unknown teacher"})
    month = body.month.replace(day=1)
    if await _month_paid(db, teacher.id, month):
        raise invalid(
            "That month's salary is already paid; deduct the advance from a later month.", {"month": "Already paid"}
        )
    adv = SalaryAdvance(teacher_id=teacher.id, amount=money(body.amount), month=month, note=body.note)
    db.add(adv)
    await db.flush()
    log_action(
        actor, "create", "salary_advance", adv.id, {"amount": str(adv.amount), "month": str(month)}, db=db, ip=ip
    )
    await db.commit()
    return AdvanceOut(
        id=adv.id, teacher_id=teacher.id, teacher_name=teacher.full_name, amount=adv.amount, month=month, note=adv.note
    )


async def list_advances(db: AsyncSession, month: date) -> list[AdvanceOut]:
    first, _ = _month_bounds(month)
    rows = await db.execute(
        select(SalaryAdvance, Teacher.full_name)
        .join(Teacher, Teacher.id == SalaryAdvance.teacher_id)
        .where(SalaryAdvance.month == first)
        .order_by(Teacher.full_name)
    )
    return [
        AdvanceOut(id=a.id, teacher_id=a.teacher_id, teacher_name=n, amount=a.amount, month=a.month, note=a.note)
        for a, n in rows.all()
    ]


async def delete_advance(db: AsyncSession, actor: User, advance_id: uuid.UUID, ip: str | None) -> None:
    adv = await db.get(SalaryAdvance, advance_id)
    if adv is None:
        raise not_found("Advance")
    if await _month_paid(db, adv.teacher_id, adv.month):
        raise conflict("That month's salary is already paid.", code="already_paid")
    await db.delete(adv)
    log_action(actor, "delete", "salary_advance", advance_id, {"amount": str(adv.amount)}, db=db, ip=ip)
    await db.commit()
